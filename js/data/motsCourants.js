// LES MOTS DU CHEMIN — le français courant qui porte le jardin.
//
// ─────────────────────────────────────────────────────────────────────────────
//
// POURQUOI CE FICHIER EXISTE, ET POURQUOI IL N'EST PAS DU VOCABULAIRE DE MATHS.
//
// RÉMY : « j'adore le jeu rows garden qui était souvent sur world of puzzles,
// on pourrait le faire en français avec des mots de math ».
//
// Le Rows Garden est un champ d'hexagones où chaque RANGÉE porte deux réponses
// et chaque FLEUR un mot de six lettres. Dans sa forme d'origine les fleurs
// PAVENT le champ : chaque case appartient à une fleur ET à une rangée, donc
// chaque lettre est contrainte deux fois. C'est ce qui rend le jeu si dense —
// et si vorace.
//
// MESURÉ (`node tools/jardinPossible.mjs`), et de plusieurs façons :
//
//   · le dépôt portait 237 mots, soit 30 à 40 par longueur ;
//   · sur le plus petit jardin pavé — quatre fleurs, vingt-huit cases —, la
//     recherche EXHAUSTIVE trouve ZÉRO remplissage. Pas « difficile » : aucun ;
//   · un jardin à SIX fleurs — le minimum pour que les indices rangés par
//     couleur cachent quelque chose, deux fleurs par couleur — se remplit
//     1 fois sur 6 à cent mots par longueur, 3 sur 6 à deux cent cinquante,
//     6 sur 6 à quatre cents ;
//   · et les mots RÉELS ne remplissent ni mieux ni moins bien qu'un tirage au
//     hasard de même taille (8/8 contre 8/8) : le chiffre vaut donc pour du
//     vrai vocabulaire, ce n'est pas un artefact de la mesure.
//
// LE VOCABULAIRE MATHÉMATIQUE DU COLLÈGE NE LES A PAS, et ne les aura jamais :
// il n'existe pas cent cinquante mots de maths de cinq lettres. C'est un
// plafond de la langue, pas du logiciel.
//
// ─────────────────────────────────────────────────────────────────────────────
//
// LE REMÈDE EST CELUI DE LA PYRAMIDE, et le dépôt l'avait déjà trouvé.
//
// `js/data/motsPyramide.js`, en tête : « Le but était tout de même d'avoir à la
// fin des mots mathématiques. On avait conclu l'inverse — la contrainte est
// terrible […] et le lexique des mathématiques est bien trop petit pour la
// porter d'un bout à l'autre. Ce n'est pas vrai pour son SOMMET. »
//
// LE CHEMIN EST EN FRANÇAIS COURANT, L'ARRIVÉE EST EN MATHS. Dans le jardin,
// les FLEURS seront prises d'abord dans le lexique mathématique — ce sont elles
// qu'on retient, elles sont au centre du dessin et leur définition est une
// définition de cours. Les rangées acceptent en plus les mots d'ici.
//
// ─────────────────────────────────────────────────────────────────────────────
//
// CE QUE CE FICHIER NE DOIT JAMAIS ALIMENTER.
//
// Les mots cachés, les mots croisés, le mot codé et les anagrammes sont des
// exercices de VOCABULAIRE MATHÉMATIQUE : on y cherche « hypoténuse » et
// « médiatrice », et chaque mot trouvé rend sa définition de cours. Y verser
// « BATEAU » et « CHEMISE » les transformerait en passe-temps. Ils gardent
// `LEXIQUE` (js/core/motsCaches.js), et rien d'autre.
//
// ON PEUT EN REVANCHE le donner à la pyramide, dont les barreaux du milieu sont
// déjà du français courant, et c'est le même rôle exactement.
//
// ─────────────────────────────────────────────────────────────────────────────
//
// COMMENT SONT ÉCRITES LES DÉFINITIONS.
//
// Courtes, et lisibles par un élève de sixième. Elles ne contiennent jamais le
// mot qu'elles définissent ni un mot de la même famille. Quand un mot a
// plusieurs sens, on prend le plus concret — c'est une grille, pas un
// dictionnaire. Les mots sont en MAJUSCULES SANS ACCENT, comme tout le reste
// du dépôt : une grille ne porte pas d'accent, et « ÉLÈVE » s'y écrit ELEVE.

