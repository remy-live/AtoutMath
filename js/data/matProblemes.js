// LES POSITIONS DE MAT — cent neuf, rangées par difficulté.
//
// AUCUNE N'A ÉTÉ ÉCRITE À LA MAIN. Elles ont été tirées au hasard puis passées
// au solveur (core/mat.js, bâti sur un moteur validé au perft), et seules ont
// été gardées celles qui vérifient les trois conditions d'un bon problème :
//
//   · LA POSITION EST LÉGALE — les Noirs n'y sont pas déjà en échec, ce qui ne
//     peut pas arriver dans une partie et donnerait un « mat » qui prend le roi ;
//   · LA SOLUTION EST UNIQUE — sinon l'élève qui trouve l'autre a raison et la
//     correction lui donne tort ;
//   · LA LONGUEUR ANNONCÉE EST LA VRAIE — un « mat en deux » qui se mate en un
//     n'est pas un mat en deux.
//
// Les tests repassent ces trois conditions sur CHAQUE position à chaque
// exécution : le fichier ne peut pas se dégrader en silence.
//
// LA PROGRESSION EST DANS LE MATÉRIEL, pas dans une note de difficulté arbitraire.
// On commence par une dame qui fait tout le travail, on finit par deux tours qui
// doivent se coordonner en deux coups. Dans un même niveau, les positions sont
// rangées du moins ramifié au plus ramifié : moins de coups possibles, c'est
// moins de choses à écarter.

